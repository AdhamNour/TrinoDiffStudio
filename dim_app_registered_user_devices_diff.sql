        TRIM(CAST(o.registration_time_key AS VARCHAR)) AS o_registration_time_key,
        TRIM(CAST(CAST(o.unblock_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_unblock_time,
        TRIM(CAST(o.unblock_time_key AS VARCHAR)) AS o_unblock_time_key,
        TRIM(CAST(o.updated_by AS VARCHAR)) AS o_updated_by,
