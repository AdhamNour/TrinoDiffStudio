           ROW(o.block_created_by, o.block_created_on, o.block_updated_by, o.block_updated_on, o.blocked_time, o.blocked_time_key, o.created_by, o.created_on, o.customer_id, o.deregistration_time, o.deregistration_time_key, o.device_id, o.device_ip_address, o.device_latitude, o.device_location, o.device_longitude, o.device_model, o.device_name, o.device_os_type_description, o.device_os_type_id, o.device_os_type_name, o.device_os_version, o.device_status_type_description, o.device_status_type_id, o.device_status_type_name, o.extraction_time_slot, o.extraction_timestamp, o.flag_active, o.flag_block_active, o.flag_registered_device, o.registered_user_id, o.registration_time, o.registration_time_key, o.unblock_time, o.unblock_time_key, o.updated_by, o.updated_on, o.user_devices_key)
    )
),
