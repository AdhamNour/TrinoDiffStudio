WITH diff_data AS (
    SELECT
        COALESCE(p.registered_user_id, o.registered_user_id) AS registered_user_id,
        CASE
            WHEN p.registered_user_id IS NULL THEN 'ONLY_IN_ORACLE'
            WHEN o.registered_user_id IS NULL THEN 'ONLY_IN_POSTGRES'
            ELSE 'VALUE_MISMATCH'
        END AS row_diff_type,

        -- Postgres values cast to VARCHAR for uniform unpivoting
        TRIM(CAST(p.biometrics_type_description AS VARCHAR)) AS p_biometrics_type_description,
        TRIM(CAST(p.biometrics_type_id AS VARCHAR)) AS p_biometrics_type_id,
        TRIM(CAST(p.biometrics_type_name AS VARCHAR)) AS p_biometrics_type_name,
        TRIM(CAST(p.created_by AS VARCHAR)) AS p_created_by,
        TRIM(CAST(CAST(p.created_on AS TIMESTAMP(0)) AS VARCHAR)) AS p_created_on,
        TRIM(CAST(p.customer_id AS VARCHAR)) AS p_customer_id,
        TRIM(CAST(p.extraction_time_slot AS VARCHAR)) AS p_extraction_time_slot,
        TRIM(CAST(CAST(p.extraction_timestamp AS TIMESTAMP(0)) AS VARCHAR)) AS p_extraction_timestamp,
        TRIM(CAST(p.failed_login_count AS VARCHAR)) AS p_failed_login_count,
        TRIM(CAST(p.flag_biometrics_enabled AS VARCHAR)) AS p_flag_biometrics_enabled,
        TRIM(CAST(p.flag_passcode_set AS VARCHAR)) AS p_flag_passcode_set,
        TRIM(CAST(p.isva_user_id AS VARCHAR)) AS p_isva_user_id,
        TRIM(CAST(CAST(p.last_180_days_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_last_180_days_time,
        TRIM(CAST(p.last_180_days_time_key AS VARCHAR)) AS p_last_180_days_time_key,
        TRIM(CAST(CAST(p.last_90_days_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_last_90_days_time,
        TRIM(CAST(p.last_90_days_time_key AS VARCHAR)) AS p_last_90_days_time_key,
        TRIM(CAST(p.last_user_status_update_key AS VARCHAR)) AS p_last_user_status_update_key,
        TRIM(CAST(CAST(p.last_user_status_update_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_last_user_status_update_time,
        TRIM(CAST(p.mobile_number AS VARCHAR)) AS p_mobile_number,
        TRIM(CAST(CAST(p.nafath_reset_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_nafath_reset_time,
        TRIM(CAST(p.nafath_reset_time_key AS VARCHAR)) AS p_nafath_reset_time_key,
        TRIM(CAST(p.nafath_usage_count AS VARCHAR)) AS p_nafath_usage_count,
        TRIM(CAST(p.original_user_status_id AS VARCHAR)) AS p_original_user_status_id,
        TRIM(CAST(p.registered_user_key AS VARCHAR)) AS p_registered_user_key,
        TRIM(CAST(CAST(p.registration_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_registration_time,
        TRIM(CAST(p.registration_time_key AS VARCHAR)) AS p_registration_time_key,
        TRIM(CAST(p.second_login_flag AS VARCHAR)) AS p_second_login_flag,
        TRIM(CAST(p.updated_by AS VARCHAR)) AS p_updated_by,
        TRIM(CAST(CAST(p.updated_on AS TIMESTAMP(0)) AS VARCHAR)) AS p_updated_on,
        TRIM(CAST(p.user_name AS VARCHAR)) AS p_user_name,
        TRIM(CAST(p.user_status_description AS VARCHAR)) AS p_user_status_description,
        TRIM(CAST(p.user_status_id AS VARCHAR)) AS p_user_status_id,
        TRIM(CAST(p.user_status_name AS VARCHAR)) AS p_user_status_name,

        -- Oracle values cast to VARCHAR for uniform unpivoting
        TRIM(CAST(o.biometrics_type_description AS VARCHAR)) AS o_biometrics_type_description,
        TRIM(CAST(o.biometrics_type_id AS VARCHAR)) AS o_biometrics_type_id,
        TRIM(CAST(o.biometrics_type_name AS VARCHAR)) AS o_biometrics_type_name,
        TRIM(CAST(o.created_by AS VARCHAR)) AS o_created_by,
        TRIM(CAST(CAST(o.created_on AS TIMESTAMP(0)) AS VARCHAR)) AS o_created_on,
        TRIM(CAST(o.customer_id AS VARCHAR)) AS o_customer_id,
        TRIM(CAST(o.extraction_time_slot AS VARCHAR)) AS o_extraction_time_slot,
        TRIM(CAST(CAST(o.extraction_timestamp AS TIMESTAMP(0)) AS VARCHAR)) AS o_extraction_timestamp,
        TRIM(CAST(o.failed_login_count AS VARCHAR)) AS o_failed_login_count,
        TRIM(CAST(o.flag_biometrics_enabled AS VARCHAR)) AS o_flag_biometrics_enabled,
        TRIM(CAST(o.flag_passcode_set AS VARCHAR)) AS o_flag_passcode_set,
        TRIM(CAST(o.isva_user_id AS VARCHAR)) AS o_isva_user_id,
        TRIM(CAST(CAST(o.last_180_days_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_last_180_days_time,
        TRIM(CAST(o.last_180_days_time_key AS VARCHAR)) AS o_last_180_days_time_key,
        TRIM(CAST(CAST(o.last_90_days_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_last_90_days_time,
        TRIM(CAST(o.last_90_days_time_key AS VARCHAR)) AS o_last_90_days_time_key,
        TRIM(CAST(o.last_user_status_update_key AS VARCHAR)) AS o_last_user_status_update_key,
        TRIM(CAST(CAST(o.last_user_status_update_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_last_user_status_update_time,
        TRIM(CAST(o.mobile_number AS VARCHAR)) AS o_mobile_number,
        TRIM(CAST(CAST(o.nafath_reset_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_nafath_reset_time,
        TRIM(CAST(o.nafath_reset_time_key AS VARCHAR)) AS o_nafath_reset_time_key,
        TRIM(CAST(o.nafath_usage_count AS VARCHAR)) AS o_nafath_usage_count,
        TRIM(CAST(o.original_user_status_id AS VARCHAR)) AS o_original_user_status_id,
        TRIM(CAST(o.registered_user_key AS VARCHAR)) AS o_registered_user_key,
        TRIM(CAST(CAST(o.registration_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_registration_time,
        TRIM(CAST(o.registration_time_key AS VARCHAR)) AS o_registration_time_key,
        TRIM(CAST(o.second_login_flag AS VARCHAR)) AS o_second_login_flag,
        TRIM(CAST(o.updated_by AS VARCHAR)) AS o_updated_by,
        TRIM(CAST(CAST(o.updated_on AS TIMESTAMP(0)) AS VARCHAR)) AS o_updated_on,
        TRIM(CAST(o.user_name AS VARCHAR)) AS o_user_name,
        TRIM(CAST(o.user_status_description AS VARCHAR)) AS o_user_status_description,
        TRIM(CAST(o.user_status_id AS VARCHAR)) AS o_user_status_id,
        TRIM(CAST(o.user_status_name AS VARCHAR)) AS o_user_status_name
    FROM postgres.curated.dim_app_registered_users p
    FULL OUTER JOIN oracle.curated.dim_app_registered_users o
        ON p.registered_user_id = o.registered_user_id
    WHERE (
        p.registered_user_id IS NULL
        OR o.registered_user_id IS NULL
        OR ROW(p.biometrics_type_description, p.biometrics_type_id, p.biometrics_type_name, p.created_by, p.created_on, p.customer_id, p.extraction_time_slot, p.extraction_timestamp, p.failed_login_count, p.flag_biometrics_enabled, p.flag_passcode_set, p.isva_user_id, p.last_180_days_time, p.last_180_days_time_key, p.last_90_days_time, p.last_90_days_time_key, p.last_user_status_update_key, p.last_user_status_update_time, p.mobile_number, p.nafath_reset_time, p.nafath_reset_time_key, p.nafath_usage_count, p.original_user_status_id, p.registered_user_key, p.registration_time, p.registration_time_key, p.second_login_flag, p.updated_by, p.updated_on, p.user_name, p.user_status_description, p.user_status_id, p.user_status_name)
           IS DISTINCT FROM
           ROW(o.biometrics_type_description, o.biometrics_type_id, o.biometrics_type_name, o.created_by, o.created_on, o.customer_id, o.extraction_time_slot, o.extraction_timestamp, o.failed_login_count, o.flag_biometrics_enabled, o.flag_passcode_set, o.isva_user_id, o.last_180_days_time, o.last_180_days_time_key, o.last_90_days_time, o.last_90_days_time_key, o.last_user_status_update_key, o.last_user_status_update_time, o.mobile_number, o.nafath_reset_time, o.nafath_reset_time_key, o.nafath_usage_count, o.original_user_status_id, o.registered_user_key, o.registration_time, o.registration_time_key, o.second_login_flag, o.updated_by, o.updated_on, o.user_name, o.user_status_description, o.user_status_id, o.user_status_name)
    )
),
