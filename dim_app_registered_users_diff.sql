            d.o_last_180_days_time_key,
            d.o_last_90_days_time,
            d.o_last_90_days_time_key,
            d.o_last_user_status_update_key,
            d.o_last_user_status_update_time,
            d.o_mobile_number,
            d.o_nafath_reset_time,
            d.o_nafath_reset_time_key,
            d.o_nafath_usage_count,
            d.o_original_user_status_id,
            d.o_registered_user_key,
            d.o_registration_time,
            d.o_registration_time_key,
            d.o_second_login_flag,
            d.o_updated_by,
            d.o_updated_on,
            d.o_user_name,
            d.o_user_status_description,
            d.o_user_status_id,
            d.o_user_status_name
        ]
    ) AS u(column_name, postgres_value, oracle_value)
WHERE
    u.postgres_value IS DISTINCT FROM u.oracle_value
    AND u.column_name NOT LIKE '%key'
)
SELECT *
FROM final_result
ORDER BY 1, 2;
