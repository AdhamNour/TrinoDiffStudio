        TRIM(CAST(p.device_location AS VARCHAR)) AS p_device_location,
        TRIM(CAST(p.device_longitude AS VARCHAR)) AS p_device_longitude,
        TRIM(CAST(p.device_model AS VARCHAR)) AS p_device_model,
        TRIM(CAST(p.device_name AS VARCHAR)) AS p_device_name,
        TRIM(CAST(p.device_os_type_description AS VARCHAR)) AS p_device_os_type_description,
        TRIM(CAST(p.device_os_type_id AS VARCHAR)) AS p_device_os_type_id,
        TRIM(CAST(p.device_os_type_name AS VARCHAR)) AS p_device_os_type_name,
        TRIM(CAST(p.device_os_version AS VARCHAR)) AS p_device_os_version,
        TRIM(CAST(p.device_status_type_description AS VARCHAR)) AS p_device_status_type_description,
        TRIM(CAST(p.device_status_type_id AS VARCHAR)) AS p_device_status_type_id,
        TRIM(CAST(p.device_status_type_name AS VARCHAR)) AS p_device_status_type_name,
        TRIM(CAST(p.extraction_time_slot AS VARCHAR)) AS p_extraction_time_slot,
        TRIM(CAST(CAST(p.extraction_timestamp AS TIMESTAMP(0)) AS VARCHAR)) AS p_extraction_timestamp,
        TRIM(CAST(p.flag_active AS VARCHAR)) AS p_flag_active,
        TRIM(CAST(p.flag_block_active AS VARCHAR)) AS p_flag_block_active,
        TRIM(CAST(p.flag_registered_device AS VARCHAR)) AS p_flag_registered_device,
        TRIM(CAST(p.registered_user_id AS VARCHAR)) AS p_registered_user_id,
        TRIM(CAST(CAST(p.registration_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_registration_time,
        TRIM(CAST(p.registration_time_key AS VARCHAR)) AS p_registration_time_key,
        TRIM(CAST(CAST(p.unblock_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_unblock_time,
        TRIM(CAST(p.unblock_time_key AS VARCHAR)) AS p_unblock_time_key,
        TRIM(CAST(p.updated_by AS VARCHAR)) AS p_updated_by,
        TRIM(CAST(CAST(p.updated_on AS TIMESTAMP(0)) AS VARCHAR)) AS p_updated_on,
        TRIM(CAST(p.user_devices_key AS VARCHAR)) AS p_user_devices_key,

        -- Oracle values cast to VARCHAR for uniform unpivoting
        TRIM(CAST(o.block_created_by AS VARCHAR)) AS o_block_created_by,
        TRIM(CAST(CAST(o.block_created_on AS TIMESTAMP(0)) AS VARCHAR)) AS o_block_created_on,
        TRIM(CAST(o.block_updated_by AS VARCHAR)) AS o_block_updated_by,
        TRIM(CAST(CAST(o.block_updated_on AS TIMESTAMP(0)) AS VARCHAR)) AS o_block_updated_on,
        TRIM(CAST(CAST(o.blocked_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_blocked_time,
        TRIM(CAST(o.blocked_time_key AS VARCHAR)) AS o_blocked_time_key,
        TRIM(CAST(o.created_by AS VARCHAR)) AS o_created_by,
        TRIM(CAST(CAST(o.created_on AS TIMESTAMP(0)) AS VARCHAR)) AS o_created_on,
        TRIM(CAST(o.customer_id AS VARCHAR)) AS o_customer_id,
        TRIM(CAST(CAST(o.deregistration_time AS TIMESTAMP(0)) AS VARCHAR)) AS o_deregistration_time,
        TRIM(CAST(o.deregistration_time_key AS VARCHAR)) AS o_deregistration_time_key,
        TRIM(CAST(o.device_id AS VARCHAR)) AS o_device_id,
        TRIM(CAST(o.device_ip_address AS VARCHAR)) AS o_device_ip_address,
        TRIM(CAST(o.device_latitude AS VARCHAR)) AS o_device_latitude,
        TRIM(CAST(o.device_location AS VARCHAR)) AS o_device_location,
        TRIM(CAST(o.device_longitude AS VARCHAR)) AS o_device_longitude,
