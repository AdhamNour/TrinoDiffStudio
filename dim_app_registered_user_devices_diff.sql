        TRIM(CAST(o.user_devices_key AS VARCHAR)) AS o_user_devices_key
    FROM postgres.curated.dim_app_registered_user_devices p
    FULL OUTER JOIN oracle.curated.dim_app_registered_user_devices o
        ON p.registered_device_id = o.registered_device_id
    WHERE (
        p.registered_device_id IS NULL
        OR o.registered_device_id IS NULL
        OR ROW(p.block_created_by, p.block_created_on, p.block_updated_by, p.block_updated_on, p.blocked_time, p.blocked_time_key, p.created_by, p.created_on, p.customer_id, p.deregistration_time, p.deregistration_time_key, p.device_id, p.device_ip_address, p.device_latitude, p.device_location, p.device_longitude, p.device_model, p.device_name, p.device_os_type_description, p.device_os_type_id, p.device_os_type_name, p.device_os_version, p.device_status_type_description, p.device_status_type_id, p.device_status_type_name, p.extraction_time_slot, p.extraction_timestamp, p.flag_active, p.flag_block_active, p.flag_registered_device, p.registered_user_id, p.registration_time, p.registration_time_key, p.unblock_time, p.unblock_time_key, p.updated_by, p.updated_on, p.user_devices_key)
