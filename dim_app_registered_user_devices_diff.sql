    SELECT
        COALESCE(p.registered_device_id, o.registered_device_id) AS registered_device_id,
        CASE
            WHEN p.registered_device_id IS NULL THEN 'ONLY_IN_ORACLE'
            WHEN o.registered_device_id IS NULL THEN 'ONLY_IN_POSTGRES'
            ELSE 'VALUE_MISMATCH'
        END AS row_diff_type,

        -- Postgres values cast to VARCHAR for uniform unpivoting
        TRIM(CAST(p.block_created_by AS VARCHAR)) AS p_block_created_by,
        TRIM(CAST(CAST(p.block_created_on AS TIMESTAMP(0)) AS VARCHAR)) AS p_block_created_on,
        TRIM(CAST(p.block_updated_by AS VARCHAR)) AS p_block_updated_by,
        TRIM(CAST(CAST(p.block_updated_on AS TIMESTAMP(0)) AS VARCHAR)) AS p_block_updated_on,
        TRIM(CAST(CAST(p.blocked_time AS TIMESTAMP(0)) AS VARCHAR)) AS p_blocked_time,
        TRIM(CAST(p.blocked_time_key AS VARCHAR)) AS p_blocked_time_key,
        TRIM(CAST(p.created_by AS VARCHAR)) AS p_created_by,
        TRIM(CAST(CAST(p.created_on AS TIMESTAMP(0)) AS VARCHAR)) AS p_created_on,
        TRIM(CAST(p.customer_id AS VARCHAR)) AS p_customer_id,
